#!/usr/bin/env bash
# 매 회차 읽는 문서가 부풀지 않게 상한을 강제한다.
#
# 왜 게이트인가: 「문서를 얇게 유지하라」를 규칙으로만 적어두면 반드시 어겨진다.
# 1판은 매 회차 읽는 문서가 758+1012+826 줄까지 불어서 한 회차가 20분이 됐다.
# 상한은 상태 검사 안에 인자로 박혀 있고 상태 검사는 무장돼 있으므로 세션이 못 늘린다.
#
# **상한은 어떻게 정하나 — `NUMBERS.md` 18절에 잰 값과 함께 있다.**
# 두 종류가 섞여 있으니 새 파일을 얹을 때 어느 쪽인지 먼저 정한다:
#   ① **매 턴 문맥에 들어가는 파일** (`CLAUDE.md` · `docs/PROMPT.md`)
#      한 줄 ≈ 48토큰이고 **턴 수만큼 곱해진다** (실행 005 는 115턴 = 한 줄 5,520토큰).
#      상한은 「지금 길이 + 약 25%」다. 여기서 부풀면 회차 비용이 바로 오른다.
#   ② **잘라내는 쪽을 감시하는 파일** (`.loop/state.md`)
#      세션에게 가는 것은 `state.py tail 2` 뿐이라 파일 길이는 비용이 아니다.
#      상한이 막는 것은 **`roll_state` 가 안 돌았을 때**다. 그래서 상한은
#      「머리말 + 남기는 절 수 × 가장 긴 절」로 잡는다 — 실측 최악 67줄.
# 90 은 ①이 아니라 ②인데 **`STATE_KEEP=3` + 자르기가 판정 뒤였던 시절**의 값이다
# (절 3개 59줄 + 안 잘린 절 하나 ~28줄 ≈ 87 → 90). 두 전제 다 회차 26·43 에 사라졌다.
#
# 사용법: doclen.sh <파일>:<최대줄> ...
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"; cd "$ROOT"
bad=0
for spec in "$@"; do
  f="${spec%%:*}"; max="${spec##*:}"
  if [ ! -f "$f" ]; then echo "DOCLEN 없는 파일: $f"; bad=1; continue; fi
  n="$(wc -l < "$f" | tr -d ' ')"
  if [ "$n" -gt "$max" ]; then
    echo "DOCLEN $f  잰 값 ${n}줄 · 상한 ${max}줄  ← 부풀었다"; bad=1
  else
    echo "DOCLEN $f  ${n}/${max}줄"
  fi
done
[ "$bad" -eq 0 ] || { echo "매 회차 읽는 문서가 부풀었다. 조건부로 읽는 파일로 옮겨라."; exit 1; }
